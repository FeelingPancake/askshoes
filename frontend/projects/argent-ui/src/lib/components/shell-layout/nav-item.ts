/**
 * Пункт верхней навигации {@link ShellLayout}. Ядро не знает разделов
 * конкретного приложения — массив пунктов целиком задаёт приложение.
 *
 * Навигация двухуровневая: пункты верхнего уровня — первая строка вкладок,
 * их `children` — вторая строка (у активного раздела). Более глубокая
 * вложенность не поддерживается.
 *
 * @example
 * ```ts
 * const nav: ArgentNavItem[] = [
 *   { label: 'Дашборд', route: '/dashboard' },
 *   {
 *     label: 'Заказы',
 *     route: '/orders',
 *     children: [{ label: 'Приёмка', route: '/orders/reception' }],
 *   },
 * ];
 * ```
 */
export interface ArgentNavItem {
  /** Подпись вкладки. */
  label: string;
  /** Абсолютный путь маршрута без `?…`/`#…`, например `'/orders'`. */
  route: string;
  /** Подразделы — вторая строка вкладок. Максимум два уровня. */
  children?: ArgentNavItem[];
}
